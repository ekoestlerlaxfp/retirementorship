export type TipProgress = { index: number; day: string };
export function localTipDay(date = new Date()): string {
  return `${date.getFullYear()}-${date.getMonth() + 1}-${date.getDate()}`;
}
export function restoreTipProgress(raw: string | null, day: string): TipProgress {
  try {
    const saved = JSON.parse(raw || "null");
    if (saved && Number.isInteger(saved.index) && saved.index >= 0 && saved.index < retirementTips.length && typeof saved.day === "string") {
      return saved.day === day ? saved : advanceTip(saved, day);
    }
  } catch { /* Missing or damaged storage starts a fresh cycle. */ }
  return { index: 0, day };
}
export function advanceTip(progress: TipProgress, day: string): TipProgress {
  return { index: (progress.index + 1) % retirementTips.length, day };
}
